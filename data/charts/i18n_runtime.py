def translate_ui_text(value: Any) -> Any:
    """Translate fixed display text while preserving non-string values."""
    if not isinstance(value, str) or not value:
        return value
    translated = value
    for english, chinese in sorted(_PHRASES.items(), key=lambda item: len(item[0]), reverse=True):
        phrase_pattern = re.escape(english).replace(r"\ ", r"\s+")
        pattern = rf"(?<![A-Za-z0-9_]){phrase_pattern}(?![A-Za-z0-9_])"
        translated = re.sub(pattern, lambda _match: chinese, translated)
    return translated


def _localized_column_config(data: Any, existing: dict | None) -> dict:
    columns = getattr(data, "columns", None)
    if columns is None and hasattr(data, "data"):
        columns = getattr(data.data, "columns", None)
    config = dict(existing or {})
    if columns is None:
        return config
    for column in columns:
        if column in config:
            continue
        raw = str(column)
        display = _COLUMN_NAMES.get(raw, translate_ui_text(raw))
        if display != raw:
            config[column] = display
    return config


def _localized_dataframe_values(data: Any) -> Any:
    """Translate visible string cells without changing model-side dataframes."""
    if isinstance(data, pd.DataFrame):
        localized = data.copy()
        for column in localized.columns:
            if pd.api.types.is_object_dtype(localized[column].dtype) or pd.api.types.is_string_dtype(localized[column].dtype):
                localized[column] = localized[column].map(translate_ui_text)
        return localized
    # A Styler is already a presentation object created for this one render.  A
    # formatter changes only its displayed strings and preserves color styles.
    if hasattr(data, "data") and isinstance(getattr(data, "data", None), pd.DataFrame):
        formatters = {}
        for column in data.data.columns:
            series = data.data[column]
            if pd.api.types.is_object_dtype(series.dtype) or pd.api.types.is_string_dtype(series.dtype):
                formatters[column] = translate_ui_text
        if formatters:
            data = data.format(formatters)
        data = data.format_index(
            lambda value: translate_ui_text(str(value)), axis=0
        ).format_index(
            lambda value: translate_ui_text(str(value)), axis=1
        )
    return data


def _localize_plotly(figure: Any) -> Any:
    if not hasattr(figure, "to_dict"):
        return figure
    payload = deepcopy(figure.to_dict())

    def walk(node: Any, parent_key: str = "") -> None:
        if isinstance(node, dict):
            for key, item in list(node.items()):
                if isinstance(item, str) and key in {"text", "name", "hovertemplate"}:
                    node[key] = translate_ui_text(item)
                else:
                    walk(item, key)
        elif isinstance(node, list):
            for index, item in enumerate(node):
                if isinstance(item, str) and parent_key in {
                    "text", "name", "hovertemplate"
                }:
                    node[index] = translate_ui_text(item)
                else:
                    walk(item, parent_key)

    walk(payload)
    return go.Figure(payload)


def _first_arg_translator(original: Callable, keyword: str) -> Callable:
    def wrapped(*args, **kwargs):
        if args:
            args = (translate_ui_text(args[0]), *args[1:])
        elif keyword in kwargs:
            kwargs[keyword] = translate_ui_text(kwargs[keyword])
        return original(*args, **kwargs)
    return wrapped


@contextmanager
def localized_streamlit_output():
    """Temporarily localize Streamlit output for one page render."""
    if current_language() != LANG_ZH:
        yield
        return

    originals: dict[str, Callable] = {}
    simple_methods = {
        "markdown": "body", "caption": "body", "warning": "body",
        "info": "body", "error": "body", "success": "body",
        "expander": "label", "button": "label", "download_button": "label",
        "spinner": "text",
    }
    try:
        for name, keyword in simple_methods.items():
            originals[name] = getattr(st, name)
            setattr(st, name, _first_arg_translator(originals[name], keyword))

        for name in ("selectbox", "radio"):
            original = getattr(st, name)
            originals[name] = original

            def make_widget_wrapper(func: Callable) -> Callable:
                def wrapped(label, options, *args, **kwargs):
                    original_format = kwargs.get("format_func", str)
                    kwargs["format_func"] = lambda option: translate_ui_text(
                        original_format(option)
                    )
                    return func(translate_ui_text(label), options, *args, **kwargs)
                return wrapped

            setattr(st, name, make_widget_wrapper(original))

        originals["slider"] = st.slider

        def localized_slider(label, *args, **kwargs):
            return originals["slider"](translate_ui_text(label), *args, **kwargs)

        st.slider = localized_slider

        originals["tabs"] = st.tabs

        def localized_tabs(labels, *args, **kwargs):
            return originals["tabs"](
                [translate_ui_text(label) for label in labels], *args, **kwargs
            )

        st.tabs = localized_tabs

        originals["metric"] = st.metric

        def localized_metric(label, value, *args, **kwargs):
            if "help" in kwargs:
                kwargs["help"] = translate_ui_text(kwargs["help"])
            return originals["metric"](
                translate_ui_text(label), translate_ui_text(value), *args, **kwargs
            )

        st.metric = localized_metric

        originals["dataframe"] = st.dataframe

        def localized_dataframe(data=None, *args, **kwargs):
            config = _localized_column_config(data, kwargs.get("column_config"))
            if config:
                kwargs["column_config"] = config
            return originals["dataframe"](
                _localized_dataframe_values(data), *args, **kwargs
            )

        st.dataframe = localized_dataframe

        originals["plotly_chart"] = st.plotly_chart

        def localized_plotly_chart(figure_or_data, *args, **kwargs):
            return originals["plotly_chart"](
                _localize_plotly(figure_or_data), *args, **kwargs
            )

        st.plotly_chart = localized_plotly_chart
        yield
    finally:
        for name, original in originals.items():
            setattr(st, name, original)
